/**
 * Traditional to Simplified Chinese mapping (reverse of S2T_MAP)
 */
const T2S_MAP: Record<string, string> = Object.entries(S2T_MAP).reduce(
  (acc, [simplified, traditional]) => {
    acc[traditional] = simplified;
    return acc;
  },
  {} as Record<string, string>
);

/**
 * Convert Simplified Chinese to Traditional Chinese
 */
export function s2t(text: string): ConversionResult<string> {
  const startTime = performance.now();

  try {
    let result = '';
    let i = 0;
    while (i < text.length) {
      // Try to match 2-character phrases first
      if (i + 1 < text.length) {
        const twoChar = text.slice(i, i + 2);
        if (S2T_MAP[twoChar]) {
          result += S2T_MAP[twoChar];
          i += 2;
          continue;
        }
      }
      // Fall back to single character
      const char = text[i];
      result += S2T_MAP[char] || char;
      i++;
    }

    const endTime = performance.now();
    return {
      success: true,
      result,
      metadata: {
        duration: Math.round(endTime - startTime),
        inputLength: text.length,
        outputLength: result.length,
        extra: {
          charsConverted: result.length - (text.length - countChineseChars(text)),
        },
      },
    };
  } catch (error) {
    return {
      success: false,
      error: error instanceof Error ? error.message : 'Failed to convert to traditional Chinese',
      metadata: {
        duration: Math.round(performance.now() - startTime),
        inputLength: text.length,
      },
    };
  }
}

